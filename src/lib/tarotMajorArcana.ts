export function getCard(number: number): MajorArcanaCard {
  return MAJOR_ARCANA[((number % 22) + 22) % 22];
}

export interface LifePathResult {
  /** The final reduced primary number (0-22, where 22 is displayed as the special 0/4 dual case). */
  primary: number;
  /** For the 22 -> 愚人/皇帝 special case, the paired card number (4). Otherwise null. */
  dualNumber: number | null;
  /** For a primary in 10-21, the full recursive single-digit reduction chain (e.g. 19 -> [19, 10, 1]). Empty for 0-9 and for the 22 special case. */
  supplementChain: number[];
}

function sumAllDigits(value: number): number {
  return String(Math.abs(value))
    .split("")
    .reduce((sum, ch) => sum + Number(ch), 0);
}

function reduceToAtMost(value: number, max: number): number {
  let n = value;
  while (n > max) {
    n = sumAllDigits(n);
  }
  return n;
}

/**
 * Life-path major-arcana number from a birthdate: sum every digit of the full
 * YYYY/MM/DD, reduce repeatedly (digit-sum) until <= 22.
 */
export function computeLifePathNumber(year: number, month: number, day: number): LifePathResult {
  const raw = sumAllDigits(year) + sumAllDigits(month) + sumAllDigits(day);
  const reduced = reduceToAtMost(raw, 22);

  if (reduced === 22) {
    return { primary: 0, dualNumber: 4, supplementChain: [] };
  }

  if (reduced >= 10 && reduced <= 21) {
    const chain: number[] = [reduced];
    let n = reduced;
    while (n > 9) {
      n = sumAllDigits(n);
      chain.push(n);
    }
    return { primary: reduced, dualNumber: null, supplementChain: chain };
  }

  return { primary: reduced, dualNumber: null, supplementChain: [] };
}
