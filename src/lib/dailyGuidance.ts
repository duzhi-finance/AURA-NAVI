function dayIndex(date: Date): number {
  return date.getFullYear() * 372 + date.getMonth() * 31 + date.getDate();
}

export function getDailyGuidance(cardNumber: number, date: Date = new Date()): string {
  const idx = (dayIndex(date) + cardNumber) % DAILY_LINES.length;
  return DAILY_LINES[idx];
}

export function getTodayLabel(date: Date = new Date()): string {
  return `${date.getFullYear()}年${date.getMonth() + 1}月${date.getDate()}日`;
}
